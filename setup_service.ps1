#requires -Version 5.1

[CmdletBinding()]
param([int]$HealthTimeoutSeconds = 180)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"
$ProjectDir = $PSScriptRoot
$DatabaseEnvFile = Join-Path $ProjectDir ".env.db"
$ServiceEnvFile = Join-Path $ProjectDir ".env.service"
$SecretDir = Join-Path $ProjectDir "secrets"
$MasterKeyFile = Join-Path $SecretDir "credential-master-key"
$ComposeFile = Join-Path $ProjectDir "compose.yaml"

function New-RandomBase64Secret {
    param([int]$ByteCount = 32)
    $bytes = New-Object byte[] $ByteCount
    $random = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $random.GetBytes($bytes) } finally { $random.Dispose() }
    return [Convert]::ToBase64String($bytes)
}

if (-not (Test-Path -LiteralPath $DatabaseEnvFile)) {
    & (Join-Path $ProjectDir "setup_database.ps1")
    if ($LASTEXITCODE -ne 0) { throw "Database setup failed." }
}

if (-not (Test-Path -LiteralPath $ServiceEnvFile)) {
    $serviceLines = @(
        "# Generated by setup_service.ps1. Do not commit this file."
        "IMAGE_TAG=local"
        "WEB_PORT=8080"
        "WEB_COOKIE_SECURE=false"
        "WEB_SECRET_KEY=$(New-RandomBase64Secret)"
    )
    [System.IO.File]::WriteAllLines(
        $ServiceEnvFile, $serviceLines,
        [System.Text.UTF8Encoding]::new($false)
    )
    Write-Host "Created Git-ignored service settings: .env.service"
}

if (-not (Test-Path -LiteralPath $SecretDir)) {
    [void](New-Item -ItemType Directory -Path $SecretDir)
}
if (-not (Test-Path -LiteralPath $MasterKeyFile)) {
    [System.IO.File]::WriteAllText(
        $MasterKeyFile, (New-RandomBase64Secret),
        [System.Text.UTF8Encoding]::new($false)
    )
    Write-Host "Created Git-ignored credential master key."
}

$composeArguments = @(
    "compose", "-p", "ncp-report",
    "--env-file", $DatabaseEnvFile,
    "--env-file", $ServiceEnvFile,
    "-f", $ComposeFile
)

Write-Host "Building the application image..."
& docker @composeArguments build web
if ($LASTEXITCODE -ne 0) { throw "Docker image build failed." }

Write-Host "Starting database migration, web, scheduler, and workers..."
& docker @composeArguments up -d postgres migrate web scheduler worker-public worker-gov
if ($LASTEXITCODE -ne 0) { throw "Docker Compose startup failed." }

$deadline = (Get-Date).AddSeconds($HealthTimeoutSeconds)
do {
    $health = (& docker inspect --format "{{.State.Health.Status}}" ncp-report-web 2>$null).Trim()
    if ($health -eq "healthy") { break }
    if ($health -eq "unhealthy") {
        & docker @composeArguments logs --tail 80 web
        throw "Web service health check failed."
    }
    Start-Sleep -Seconds 2
} while ((Get-Date) -lt $deadline)

if ($health -ne "healthy") { throw "Web service did not become healthy in time." }
Write-Host ""
Write-Host "NCP Report Hub is ready: http://127.0.0.1:8080"
Write-Host "Create the first MSP administrator with setup_admin.ps1."
