#requires -Version 5.1

[CmdletBinding()]
param(
    [int]$HealthTimeoutSeconds = 120
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$ProjectDir = $PSScriptRoot
$ComposeFile = Join-Path $ProjectDir "compose.db.yaml"
$EnvFile = Join-Path $ProjectDir ".env.db"
$SchemaDir = Join-Path $ProjectDir "database\schema"
$VerifyFile = Join-Path $ProjectDir "database\verify_database.sql"

function New-RandomHexSecret {
    param([int]$ByteCount = 32)

    $bytes = New-Object byte[] $ByteCount
    $random = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try {
        $random.GetBytes($bytes)
    }
    finally {
        $random.Dispose()
    }
    return ([System.BitConverter]::ToString($bytes) -replace "-", "").ToLowerInvariant()
}

function New-DatabaseEnvFile {
    $lines = @(
        "# Generated by setup_database.ps1. Do not commit this file."
        "POSTGRES_VERSION=16"
        "REPORT_DB_ENABLED=true"
        "REPORT_DB_REQUIRED=true"
        "REPORT_DB_ROLE=msp"
        "REPORT_DB_SSLMODE=disable"
        "DB_HOST=127.0.0.1"
        "DB_PORT=55432"
        "DB_NAME=ncp_report"
        "DB_ADMIN_USER=ncp_admin"
        "DB_ADMIN_PASSWORD=$(New-RandomHexSecret)"
        "DB_CONTROL_APP_PASSWORD=$(New-RandomHexSecret)"
        "DB_PUBLIC_WORKER_PASSWORD=$(New-RandomHexSecret)"
        "DB_GOV_WORKER_PASSWORD=$(New-RandomHexSecret)"
        "DB_MSP_APP_PASSWORD=$(New-RandomHexSecret)"
    )
    [System.IO.File]::WriteAllLines(
        $EnvFile,
        $lines,
        [System.Text.UTF8Encoding]::new($false)
    )
}

function Read-DatabaseEnvFile {
    $values = @{}
    foreach ($line in [System.IO.File]::ReadAllLines($EnvFile)) {
        $trimmed = $line.Trim()
        if (-not $trimmed -or $trimmed.StartsWith("#")) {
            continue
        }
        $separator = $trimmed.IndexOf("=")
        if ($separator -lt 1) {
            throw "Invalid .env.db line: $line"
        }
        $key = $trimmed.Substring(0, $separator).Trim()
        $value = $trimmed.Substring($separator + 1)
        $values[$key] = $value
    }
    return $values
}

function Assert-RequiredSetting {
    param(
        [hashtable]$Settings,
        [string]$Name
    )

    if (-not $Settings.ContainsKey($Name) -or -not $Settings[$Name]) {
        throw "Missing required setting in .env.db: $Name"
    }
    if ($Settings[$Name] -match "replace-with") {
        throw "Replace the placeholder value in .env.db: $Name"
    }
}

$script:UseDockerComposePlugin = $false

function Initialize-ComposeCommand {
    if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
        throw "Docker was not found. Install and start Docker Desktop first."
    }

    & docker compose version *> $null
    if ($LASTEXITCODE -eq 0) {
        $script:UseDockerComposePlugin = $true
        return
    }

    if (Get-Command docker-compose -ErrorAction SilentlyContinue) {
        $script:UseDockerComposePlugin = $false
        return
    }

    throw "Neither 'docker compose' nor 'docker-compose' is available."
}

function Invoke-DatabaseCompose {
    param([Parameter(ValueFromRemainingArguments = $true)][string[]]$ComposeArguments)

    $baseArguments = @(
        "-p", "ncp-report",
        "--env-file", $EnvFile,
        "-f", $ComposeFile
    )
    if ($script:UseDockerComposePlugin) {
        & docker compose @baseArguments @ComposeArguments
    }
    else {
        & docker-compose @baseArguments @ComposeArguments
    }
    if ($LASTEXITCODE -ne 0) {
        throw "Docker Compose failed with exit code $LASTEXITCODE."
    }
}

foreach ($requiredPath in @($ComposeFile, $SchemaDir, $VerifyFile)) {
    if (-not (Test-Path -LiteralPath $requiredPath)) {
        throw "Required database setup path was not found: $requiredPath"
    }
}

if (-not (Test-Path -LiteralPath $EnvFile)) {
    New-DatabaseEnvFile
    Write-Host "Created Git-ignored local settings: .env.db"
}

$settings = Read-DatabaseEnvFile
foreach ($name in @(
    "DB_NAME",
    "DB_ADMIN_USER",
    "DB_ADMIN_PASSWORD",
    "DB_CONTROL_APP_PASSWORD",
    "DB_PUBLIC_WORKER_PASSWORD",
    "DB_GOV_WORKER_PASSWORD",
    "DB_MSP_APP_PASSWORD"
)) {
    Assert-RequiredSetting -Settings $settings -Name $name
}

Initialize-ComposeCommand

Write-Host "Starting PostgreSQL container..."
Invoke-DatabaseCompose -ComposeArguments @("up", "-d", "postgres")

$containerId = (
    Invoke-DatabaseCompose -ComposeArguments @("ps", "-q", "postgres") |
        Select-Object -First 1
).Trim()
if (-not $containerId) {
    throw "PostgreSQL container ID was not returned by Docker Compose."
}

$deadline = (Get-Date).AddSeconds($HealthTimeoutSeconds)
do {
    $health = (& docker inspect --format "{{.State.Health.Status}}" $containerId).Trim()
    if ($LASTEXITCODE -ne 0) {
        throw "Unable to inspect PostgreSQL container health."
    }
    if ($health -eq "healthy") {
        break
    }
    if ($health -eq "unhealthy") {
        throw "PostgreSQL container health check failed."
    }
    Start-Sleep -Seconds 2
} while ((Get-Date) -lt $deadline)

if ($health -ne "healthy") {
    throw "PostgreSQL did not become healthy within $HealthTimeoutSeconds seconds."
}

$schemaFiles = @(
    Get-ChildItem -LiteralPath $SchemaDir -Filter "*.sql" -File |
        Sort-Object Name
)
if ($schemaFiles.Count -eq 0) {
    throw "No schema SQL files were found in $SchemaDir."
}

foreach ($schemaFile in $schemaFiles) {
    $containerPath = "/opt/ncp-report/schema/$($schemaFile.Name)"
    Write-Host "Applying $($schemaFile.Name)..."
    Invoke-DatabaseCompose -ComposeArguments @(
        "exec", "-T", "postgres",
        "psql",
        "-U", $settings["DB_ADMIN_USER"],
        "-d", $settings["DB_NAME"],
        "-v", "ON_ERROR_STOP=1",
        "-f", $containerPath
    )
}

Write-Host "Verifying database schema..."
Invoke-DatabaseCompose -ComposeArguments @(
    "exec", "-T", "postgres",
    "psql",
    "-U", $settings["DB_ADMIN_USER"],
    "-d", $settings["DB_NAME"],
    "-v", "ON_ERROR_STOP=1",
    "-f", "/opt/ncp-report/verify_database.sql"
)

Write-Host ""
Write-Host "Database setup completed successfully."
Write-Host "Host: $($settings['DB_HOST']):$($settings['DB_PORT'])"
Write-Host "Database: $($settings['DB_NAME'])"
Write-Host "Credentials: .env.db (Git ignored)"
